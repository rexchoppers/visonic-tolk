package messagetest

import (
	"bytes"
	"testing"

	"github.com/rexchoppers/visonic-tolk/internal/message"
)

// The expected bytes come from running the python's MessageBuilder on
// "b0 17 51 ..." the way its send_init_message does.
func TestInitMatchesPython(t *testing.T) {
	cases := map[string]struct {
		asks []byte
		want []byte
	}{
		"nothing asked": {
			nil,
			[]byte{0x0d, 0xb0, 0x01, 0x17, 0x08, 0x01, 0xff, 0x08, 0xff, 0x02, 0x51, 0x0f, 0x00, 0x43, 0x80, 0x0a},
		},
		"two asks": {
			[]byte{0x18, 0x24},
			[]byte{0x0d, 0xb0, 0x01, 0x17, 0x09, 0x01, 0xff, 0x08, 0xff, 0x03, 0x51, 0x18, 0x24, 0x00, 0x43, 0x51, 0x0a},
		},
		"three asks": {
			[]byte{0x18, 0x24, 0x4b},
			[]byte{0x0d, 0xb0, 0x01, 0x17, 0x0a, 0x01, 0xff, 0x08, 0xff, 0x04, 0x51, 0x18, 0x24, 0x4b, 0x00, 0x43, 0x04, 0x0a},
		},
	}

	for name, c := range cases {
		if got := message.Init(c.asks); !bytes.Equal(got, c.want) {
			t.Errorf("%s: Init(%x) = %x, python gives %x", name, c.asks, got, c.want)
		}
	}
}

func TestAsksReadsTheListOutOfAB051(t *testing.T) {
	msg := []byte{0x0d, 0xb0, 0x03, 0x51, 0x08, 0xff, 0x08, 0xff, 0x03, 0x18, 0x24, 0x4b, 0x20, 0x43, 0xfc, 0x0a}

	if got, want := message.Asks(msg), []byte{0x18, 0x24, 0x4b}; !bytes.Equal(got, want) {
		t.Errorf("Asks = %x, want %x", got, want)
	}
}

func TestAsksIgnoresAnythingElse(t *testing.T) {
	cases := map[string][]byte{
		"keepalive": message.Keepalive,
		"short 51":  {0x0d, 0xb0, 0x03, 0x51, 0x08, 0xff, 0x08, 0xff, 0x05, 0x18, 0x0a},
		"timeout":   {0x0d, 0x06, 0xf9, 0x0a},
	}

	for name, msg := range cases {
		if got := message.Asks(msg); got != nil {
			t.Errorf("%s: Asks = %x, want nothing", name, got)
		}
	}
}
